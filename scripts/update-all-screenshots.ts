function updateScreenshotsInFile(filename: string, screenshots: Array<{ old: string; number: number; desc: string }>) {
  const docsPath = path.join(__dirname, '..', 'docs');
  const filePath = path.join(docsPath, filename);
  
  if (!fs.existsSync(filePath)) {
    console.warn(`⚠️  Файл не найден: ${filePath}`);
    return;
  }

  let content = fs.readFileSync(filePath, 'utf-8');
  let updated = false;

  for (const screenshot of screenshots) {
    const newFormat = `![screenshot-${String(screenshot.number).padStart(3, '0')}](screenshot-${String(screenshot.number).padStart(3, '0')}.png)\n*Скриншот ${screenshot.number}: ${screenshot.desc}*`;
    
    if (content.includes(screenshot.old)) {
      content = content.replace(screenshot.old, newFormat);
      updated = true;
      console.log(`  ✅ Обновлен скриншот ${screenshot.number}: ${screenshot.desc}`);
    }
  }

  if (updated) {
    fs.writeFileSync(filePath, content, 'utf-8');
    console.log(`📝 Файл обновлен: ${filename}\n`);
  } else {
    console.log(`ℹ️  Нет изменений в файле: ${filename}\n`);
  }
}

console.log('🔄 Начинаем обновление скриншотов во всех файлах...\n');

for (const [filename, screenshots] of Object.entries(screenshotMapping)) {
  console.log(`📄 Обрабатываем: ${filename}`);
  updateScreenshotsInFile(filename, screenshots);
}

